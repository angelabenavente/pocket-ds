import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as sass from "sass";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/foundations/data/foundations.values.generated.ts");

const primitiveNames = [
  "color-foundation-white",
  "color-foundation-black",
  "color-neutral-900",
  "color-border-subtle",
  "color-border-muted",
  "color-surface-subtle",
  "color-surface-muted",
  "color-neutral-800",
  "color-neutral-700",
  "color-badge-positive",
  "color-badge-negative",
  "space-4xs",
  "space-3xs",
  "space-2xs",
  "space-xs",
  "space-s",
  "space-m",
  "space-l",
  "space-xl",
  "space-2xl",
  "font-family-base",
  "font-family-custom",
  "font-family-base-backups",
  "font-family-custom-backups",
  "font-weight-regular",
  "font-weight-emphasis",
  "font-size-body-m",
  "font-size-body-s",
  "line-height-body",
  "letter-spacing-body",
  "font-size-heading-m",
  "line-height-heading-m",
  "font-size-heading-s",
  "line-height-heading-s",
];

const declarations = primitiveNames
  .map((name) => `  --${name}: #{p.$${name}};`)
  .concat("  --mobile-max: #{bkp.$mobile-max};")
  .join("\n");

const result = sass.compileString(
  `@use "primitives" as p;\n@use "breakpoints" as bkp;\n:root {\n${declarations}\n}`,
  { loadPaths: [resolve(root, "src/styles")], style: "expanded" },
);

const values = Object.fromEntries(
  [...result.css.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [
    name,
    value.trim(),
  ]),
);

const missingNames = [...primitiveNames, "mobile-max"].filter((name) => !(name in values));

if (missingNames.length > 0) {
  throw new Error(`Missing generated foundation values: ${missingNames.join(", ")}`);
}

const formattedValues = JSON.stringify(values, null, 2).replace(/\n}$/, ",\n}");
const output = `// Generated by scripts/generate-foundation-values.mjs. Do not edit directly.
export const foundationValues = ${formattedValues} as const;
`;

writeFileSync(outputPath, output);
